// Função para obter a imagem de um exercício
export const getExerciseImage = (exerciseName) => {
  // Retorna a imagem se existir, ou null se não encontrada
  return exerciseImages[exerciseName] || null;
};

// Função para obter uma imagem em menor resolução (para thumbnails)
export const getExerciseThumbnail = (exerciseName) => {
  const imageUrl = exerciseImages[exerciseName];
  if (!imageUrl) return null;
  
  // Modifica a URL para uma versão menor da imagem
  return imageUrl.replace('w=600', 'w=300');
};

// Função para verificar se temos mídia para um exercício
export const hasExerciseMedia = (exerciseName) => {
  return exerciseName in exerciseImages;
};

// Exporta a lista de exercícios disponíveis
export const getAvailableExercises = () => {
  return Object.keys(exerciseImages);
}; 