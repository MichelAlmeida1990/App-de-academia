// Função para definir a paleta ativa
export const setActivePalette = (paletteName) => {
  if (COLOR_PALETTES[paletteName]) {
    localStorage.setItem('activePalette', paletteName);
  }
};

// Função para obter as cores da paleta ativa
export const getPaletteColors = () => {
  const activePalette = localStorage.getItem('activePalette') || 'ocean';
  return COLOR_PALETTES[activePalette] || COLOR_PALETTES.ocean;
};

// Função para otimizar URLs de imagem com parâmetros
export const getOptimizedImage = (url, width = 400, height = null, quality = 80) => {
  if (!url) return '';
  
  try {
    const urlObj = new URL(url);
    
    // Adiciona parâmetros de otimização
    urlObj.searchParams.set('w', width.toString());
    if (height) {
      urlObj.searchParams.set('h', height.toString());
    }
    urlObj.searchParams.set('q', quality.toString());
    urlObj.searchParams.set('fit', 'crop');
    urlObj.searchParams.set('auto', 'format');
    
    return urlObj.toString();
  } catch (error) {
    console.warn('Erro ao otimizar URL da imagem:', error);
    return url;
  }
};

// Função para obter imagem com placeholder
export const getImageWithPlaceholder = (url, fallback = HERO_IMAGES.main) => {
  return url || fallback;
};

// Função para obter imagem responsiva
export const getResponsiveImage = (url, sizes = { sm: 300, md: 400, lg: 600 }) => {
  if (!url) return '';
  
  const srcSet = Object.entries(sizes)
    .map(([breakpoint, width]) => `${getOptimizedImage(url, width)} ${width}w`)
    .join(', ');
  
  return {
    src: getOptimizedImage(url, sizes.md),
    srcSet,
    sizes: `(max-width: 640px) ${sizes.sm}px, (max-width: 1024px) ${sizes.md}px, ${sizes.lg}px`
  };
}; 